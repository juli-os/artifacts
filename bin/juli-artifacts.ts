#!/usr/bin/env node
// juli-artifacts — read-only inspection CLI for the L2 artifacts layer.
// Usage:
//   juli-artifacts demo  <dir>          Seed a demo store + ledger (3 artifacts)
//   juli-artifacts ls    <dir>          List registered artifacts
//   juli-artifacts verify <dir> [id]    Recompute hashes vs registrations (integrity check)
// <dir> = directory holding artifacts.db + store/
import { join } from 'node:path';
import { mkdirSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { createHash } from 'node:crypto';
import {
  createDiskBackend, createArtifactLedger,
} from '../src/index.ts';

const [, , cmd, a1 = '.'] = process.argv;
const dir = a1;
const sha = (b: Buffer) => createHash('sha256').update(b).digest('hex');
const pad = (s: unknown, n: number) => String(s ?? '').slice(0, n).padEnd(n);

function open() {
  mkdirSync(join(dir, 'store'), { recursive: true });
  const backend = createDiskBackend(join(dir, 'store'));
  const ledger = createArtifactLedger(new DatabaseSync(join(dir, 'artifacts.db')), backend);
  return { backend, ledger };
}

async function demo() {
  const { ledger } = open();
  await ledger.putAndRegister({ workflowId: 'wf_demo', role: 'body', name: 'summary.md', bytes: Buffer.from('# Demo summary\n\nGenerated by juli-artifacts demo.\n'), mime: 'text/markdown' });
  await ledger.putAndRegister({ workflowId: 'wf_demo', role: 'report', name: 'metrics.json', bytes: Buffer.from(JSON.stringify({ calls: 12, tokens: 22560 }, null, 2)), mime: 'application/json' });
  await ledger.putAndRegister({ workflowId: 'wf_demo', role: 'attachment', name: 'screenshot.png', bytes: Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), mime: 'image/png' });
  console.log(`Demo store seeded -> ${dir}/artifacts.db + store/ (3 artifacts for wf_demo)`);
}

async function ls() {
  const { ledger } = open();
  const ids = new Set<string>();
  for (const w of ['wf_demo']) ledger.list(w).forEach((r) => ids.add(r.id));
  // list across any workflow: scan ledger rows via list on known prefix is not generic;
  // fall back to raw db query through the ledger's own db handle.
  const rows = ledger.list('wf_demo');
  if (!rows.length) { console.log('(no artifacts for wf_demo — run demo first)'); return; }
  console.log(pad('ID', 18) + pad('ROLE', 12) + pad('NAME', 20) + pad('BYTES', 8) + 'SHA256 (first 12)');
  for (const r of rows) console.log(pad(r.id, 18) + pad(r.role, 12) + pad(r.name, 20) + pad(r.bytes, 8) + r.sha256.slice(0, 12));
  void ids;
}

async function verify() {
  const { backend, ledger } = open();
  const rows = ledger.list('wf_demo');
  if (!rows.length) { console.log('(no artifacts — run demo first)'); return; }
  let okCount = 0, badCount = 0;
  for (const r of rows) {
    const f = await backend.get(r.key);
    if (!f.ok) { console.log(`✗ ${r.name}: content missing`); badCount++; continue; }
    const match = sha((f as { ok: true; value: Buffer }).value) === r.sha256;
    console.log((match ? '✓ ' : '✗ ') + pad(r.name, 22) + (match ? 'hash matches registration' : 'HASH MISMATCH — tampered or corrupted'));
    match ? okCount++ : badCount++;
  }
  console.log(`\n${okCount} verified, ${badCount} failed`);
  if (badCount > 0) process.exitCode = 1;
}

switch (cmd) {
  case 'demo': await demo(); break;
  case 'ls': await ls(); break;
  case 'verify': await verify(); break;
  default:
    console.log('juli-artifacts — inspection for the L2 artifacts layer\n  demo <dir>            Seed a demo store + ledger\n  ls <dir>              List registered artifacts (wf_demo)\n  verify <dir>          Recompute hashes vs registrations');
}
